"""デフォルト引数"""
# 例1: 全ての引数にデフォルト値がある場合
def add1(a=1, b=2):
    print(a + b)

add1()      # 出力: 3 （両方ともデフォルト値を使う）
add1(3, 2)  # 出力: 5 （渡した値で上書きする）

# 例2: 一部の引数だけにデフォルト値がある場合
def add2(a, b=2):
    print(a + b)

add2(3)    # 出力: 5 （b はデフォルト値の2を使う）
add2(a=3)  # 出力: 5 （キーワード指定でも同じ）

